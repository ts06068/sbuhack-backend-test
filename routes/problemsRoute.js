router.post(
  "/narrate",
  wrapAsync(async (req, res) => {
    const body = req.body;
    const { text } = body;

    const audio = await openai.audio.speech.create({
      model: "tts-1",
      voice: "echo",
      input: text,
    });

    const buffer = Buffer.from(await audio.arrayBuffer()).toString("base64");

    const speechFile = path.resolve("./speech.mp3");

    //upload the file to cloudinary
    const file = buffer;
    const uploadPreset = "jpxjict6"; // Add your upload preset
    const data = new FormData();
    data.append("file", file);
    data.append("upload_preset", uploadPreset);

    const response = await axios
      .post("https://api.cloudinary.com/v1_1/dwp6hrsi5/upload", data)
      .catch((err) => console.log(err));

    //send .mp3 buffer
    res.json(response);
  })
);

router.post(
  "/question",
  isLoggedIn,
  wrapAsync(async (req, res) => {
    const uid = req.session.userId;
    const body = req.body;
    const { questionTextPhoto, questionImagePhoto, isForKids } = body;

    let questionTextPhotoTranslatedText = ""; // extracted text from image of questionTextPhoto
    const answerNarrationVoice = "narration voice"; // narration voice of answerExplanationText generated by openai
    const answerVideo = "video"; // video of answerExplanationText generated by openai
    const title = "title";
    const category = "none";
    const isSaved = false;
    const lastUpdated = new Date();

    const sampleImageUrl =
      "https://res.cloudinary.com/dwp6hrsi5/image/upload/v1707447087/dino-width_cyow2b.jpg";

    const response = await openai.chat.completions.create({
      model: "gpt-4-vision-preview",
      messages: [
        {
          role: "user",
          content: [
            {
              type: "text",
              text: "There is a text in this image. Only read the text, do not add anything so that I can just copy it.",
            },
            {
              type: "image_url",
              image_url: {
                url: sampleImageUrl,
              },
            },
          ],
        },
      ],
    });

    questionTextPhotoTranslatedText = response.choices[0].message.content;

    // configure openai
    const completion = await openai.chat.completions.create({
      model: "gpt-3.5-turbo",
      messages: [
        {
          role: "system",
          content: "You are a helpful assistant", // content will change by isForKids
        },
        {
          role: "user",
          content: questionTextPhotoTranslatedText,
        },
      ],
    });

    // answerExplanationText is the string of the first message from openai
    const answerExplanationText = completion.choices
      .map((choice) => choice.message.content)
      .pop();

    const newProblem = new Problem({
      agent: uid,
      questionTextPhoto,
      questionImagePhoto,
      questionTextPhotoTranslatedText,
      answerExplanationText,
      answerNarrationVoice,
      answerVideo,
      title,
      category,
      isForKids,
      isSaved,
      lastUpdated,
    });

    const savedProblem = await newProblem.save();

    res.json({ savedProblem });
  })
);

/*
POST /problem: user likes the answer from the problem he uploaded, and adds it to favoriteProblems of User
body: _id of Problem, title, category, isForKids
server process: append _id of the new Problem to favoriteProblems of User
res: 200 (SUCCESS) 400/500 (FAILURE)
*/

router.put(
  "/favoriteProblems",
  isLoggedIn,
  wrapAsync(async (req, res) => {
    const uid = req.session.userId;
    const body = req.body;
    const { _id, title, category, isForKids } = body;
    const lastUpdated = new Date();

    //update the problem first. Update the title and category
    const problem = await Problem.findByIdAndUpdate(
      _id,
      { title, category, lastUpdated },
      { new: true }
    );

    if (!problem) {
      return res.status(400).json({ message: "Problem not found" });
    }

    //find the user and update the favoriteProblems
    const user = await User.findById(uid);

    if (!user) {
      return res.status(400).json({ message: "User not found" });
    }

    user.favoriteProblems.push(_id);
    await user.save();

    res.json({ message: "SUCCESS" });
  })
);

/*
GET /problem: user finds saved problems by category
body: category, isForKids
server process: find all problems in the category from DB
res: [_id of Problem...]
*/

router.get(
  "/question",
  isLoggedIn,
  wrapAsync(async (req, res) => {
    const uid = req.session.userId;
    const body = req.body;
    const { category, isForKids } = body;

    const problems = await Problem.find({ agent: uid, category, isForKids });

    if (!problems) {
      return res.status(400).json({ message: "Problem not found" });
    }

    res.json({ problems });
  })
);

